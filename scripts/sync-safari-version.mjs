#!/usr/bin/env node
/**
 * Generates safari/Config/Version.xcconfig from extension/manifest.json.
 *
 * extension/manifest.json is the single source of truth for FSB's version, so
 * the Xcode project must never carry its own copy. This script derives both
 * Apple version fields from it and is wired into `npm run build:safari`, so the
 * two cannot drift.
 *
 *   MARKETING_VERSION       -> CFBundleShortVersionString, the manifest version
 *                              verbatim (e.g. 0.9.90).
 *   CURRENT_PROJECT_VERSION -> CFBundleVersion. App Store Connect requires this
 *                              to STRICTLY INCREASE on every upload, which a
 *                              semver string cannot guarantee on its own
 *                              (0.9.9 -> 0.9.10 decreases lexically, and
 *                              0.10.0 < 0.9.90 numerically if you just strip
 *                              dots). Encoding each component in a fixed radix
 *                              is monotonic AND deterministic from the version
 *                              string alone:
 *
 *                                major * 1_000_000 + minor * 1_000 + patch
 *
 *                                0.9.90  -> 9090
 *                                0.9.99  -> 9099
 *                                0.10.0  -> 10000
 *                                1.0.0   -> 1000000
 *
 *                              This caps minor and patch at 999 each, which is
 *                              enforced below rather than silently wrapping.
 *
 * Usage: node scripts/sync-safari-version.mjs [--check]
 *   --check  exit non-zero if the file is stale instead of rewriting it
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const MANIFEST = join(ROOT, 'extension', 'manifest.json');
const OUT = join(ROOT, 'safari', 'Config', 'Version.xcconfig');

export function deriveVersions(manifestVersion) {
  const m = /^(\d+)\.(\d+)\.(\d+)/.exec(manifestVersion || '');
  if (!m) throw new Error(`sync-safari-version: manifest version "${manifestVersion}" is not semver-shaped`);
  const [major, minor, patch] = [Number(m[1]), Number(m[2]), Number(m[3])];
  if (minor > 999 || patch > 999) {
    throw new Error(
      `sync-safari-version: minor/patch must be <= 999 to keep CFBundleVersion monotonic ` +
      `(got ${manifestVersion}). Widen the radix in scripts/sync-safari-version.mjs before releasing this.`
    );
  }
  return {
    marketingVersion: `${major}.${minor}.${patch}`,
    currentProjectVersion: major * 1_000_000 + minor * 1_000 + patch
  };
}

export function renderXcconfig({ marketingVersion, currentProjectVersion }) {
  return [
    '// GENERATED by scripts/sync-safari-version.mjs -- DO NOT EDIT.',
    '// Source of truth: extension/manifest.json. Run `npm run build:safari`.',
    '',
    `MARKETING_VERSION = ${marketingVersion}`,
    `CURRENT_PROJECT_VERSION = ${currentProjectVersion}`,
    ''
  ].join('\n');
}

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const derived = deriveVersions(manifest.version);
const rendered = renderXcconfig(derived);

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const check = process.argv.includes('--check');
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (check) {
    if (current !== rendered) {
      console.error('sync-safari-version: Version.xcconfig is STALE. Run `node scripts/sync-safari-version.mjs`.');
      process.exit(1);
    }
    console.log(`sync-safari-version: OK (${derived.marketingVersion} / ${derived.currentProjectVersion})`);
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, rendered);
    console.log(`sync-safari-version: wrote ${derived.marketingVersion} / build ${derived.currentProjectVersion}`);
  }
}
