/**
 * Coarse, self-hosted IP -> place (country, subdivision, city) lookup for
 * anonymous aggregate telemetry.
 *
 * PRIVACY INVARIANT (mirrors src/utils/telemetry-hash.js posture):
 *   - `ip` is accepted as a function argument
 *   - it is used ONLY to compute an integer key for a binary-search range lookup
 *   - it is NEVER assigned to a module-level or long-lived variable
 *   - it is NEVER logged, NEVER written to disk, NEVER passed onward
 *   - the temporary `ip` parameter is the only place plaintext exists, and it
 *     leaves scope as soon as deriveRegion() returns
 *
 * Only the *dataset* is third-party (DB-IP IP-to-City Lite, CC-BY-4.0); the
 * lookup logic here is ours -- a sorted-range binary search over uint32 IPv4
 * forms and 64-bit IPv6 prefixes. No live third-party geo API is contacted
 * (that would leak every user's raw IP to a third party, which is worse than
 * the existing hashed-IP posture).
 *
 * SEARCHED ON DISK, NOT LOADED:
 *   City-level worldwide tables run to millions of ranges (~3.4 M IPv4, ~3.5 M
 *   IPv6 /64 prefixes) -- about 110 MB as typed arrays, which does not fit
 *   beside the server on the 256 MB Fly VM. So nothing is parsed into memory:
 *   each file stays sorted on disk and every lookup binary-searches it with
 *   positioned reads (~16 reads of 4 KiB per lookup, served from the page cache
 *   once warm). The only per-file allocation is one 64 KiB read buffer, and
 *   there is no load pause on the first request.
 *
 *   Three files, all sorted ascending and '#'/blank-line tolerant:
 *     IPv4    start_ip_int,end_ip_int,country,subdivision,city
 *     IPv6    start64,end64,country,subdivision,city    (/64 prefixes, 16 hex digits)
 *     places  label,lat,lon                              (sorted by label)
 *   Four-column range rows from the older state-level files still parse, with
 *   an empty city. The places file maps every region label the refresh script
 *   can produce (country, subdivision, and city level; see region-label.js) to
 *   an approximate centroid, so public stats can position a published place
 *   without anything location-shaped being stored per install.
 *
 *   IPv4-mapped IPv6 (`::ffff:a.b.c.d`) unwraps to IPv4; CIDR `/56` keys do not
 *   parse and stay 'unknown'. DB-IP labels private/reserved space (10/8, 127/8,
 *   ::1, fe80::, Fly 6PN fdaa::) as country 'ZZ'; that is reported as 'unknown'.
 *
 * GRACEFUL DEGRADATION (HARD requirement): if a dataset file is absent,
 * unreadable, or empty, its lookups return 'unknown' / null and this module
 * NEVER throws. The server boots and ingests with no dataset present. The real
 * artifacts are generated by scripts/refresh-dbip-dataset.mjs and are NOT
 * committed; only tiny fixtures ship for tests. A file replaced in place is not
 * noticed until restart -- the open descriptor keeps reading the old inode.
 *
 * Dataset paths: DBIP_DATASET_PATH (IPv4), DBIP_IPV6_DATASET_PATH and
 * DBIP_PLACES_DATASET_PATH, the latter two defaulting to siblings of the IPv4
 * path (`*.ipv6.csv`, `*.places.csv`, or the `.fixture.csv` forms).
 *
 * tests/server-ip-geo.test.js exercises hit / miss / absent-dataset / malformed;
 * tests/server-ip-geo-scale.test.js exercises a large synthetic dataset.
 */

'use strict';

const fs = require('fs');
const path = require('path');

// Default production artifact paths. The refresh script writes here; .gitignore
// excludes them (but keeps *.fixture.csv).
const DEFAULT_DATASET_PATH = path.join(__dirname, '..', '..', 'data', 'dbip-city-lite.csv');
const DEFAULT_IPV6_DATASET_PATH = path.join(__dirname, '..', '..', 'data', 'dbip-city-lite.ipv6.csv');
const DEFAULT_PLACES_DATASET_PATH = path.join(__dirname, '..', '..', 'data', 'dbip-city-lite.places.csv');

// Lazily-opened dataset handles. Three states each:
//   undefined -> not opened yet (open on first lookup)
//   null      -> absent / unreadable / empty (graceful 'unknown')
//   object    -> { fd, size, buf }
let _ipv4File;
let _ipv6File;
let _placesFile;

/** Sibling artifact for an IPv4 compact-CSV path: `kind` is 'ipv6' or 'places'. */
function siblingPath(ipv4Path, kind, fallback) {
  if (typeof ipv4Path !== 'string' || ipv4Path === '') return fallback;
  if (ipv4Path.endsWith('.fixture.csv')) {
    return ipv4Path.replace(/\.fixture\.csv$/, `.${kind}.fixture.csv`);
  }
  if (ipv4Path.endsWith('.csv')) return ipv4Path.slice(0, -4) + `.${kind}.csv`;
  return `${ipv4Path}.${kind}`;
}

function siblingIpv6Path(ipv4Path) {
  return siblingPath(ipv4Path, 'ipv6', DEFAULT_IPV6_DATASET_PATH);
}

function siblingPlacesPath(ipv4Path) {
  return siblingPath(ipv4Path, 'places', DEFAULT_PLACES_DATASET_PATH);
}

function resolveIpv4DatasetPath() {
  return process.env.DBIP_DATASET_PATH || DEFAULT_DATASET_PATH;
}

function resolveIpv6DatasetPath() {
  if (process.env.DBIP_IPV6_DATASET_PATH) return process.env.DBIP_IPV6_DATASET_PATH;
  return siblingIpv6Path(resolveIpv4DatasetPath());
}

function resolvePlacesDatasetPath() {
  if (process.env.DBIP_PLACES_DATASET_PATH) return process.env.DBIP_PLACES_DATASET_PATH;
  return siblingPlacesPath(resolveIpv4DatasetPath());
}


/**
 * If `ip` is an IPv4-mapped IPv6 address, return the dotted-quad IPv4 form.
 * Node and Fly both emit `::ffff:a.b.c.d` (and occasionally `:ffff:a.b.c.d`)
 * for IPv4 clients on an IPv6 socket. Unmapped IPv4 and native IPv6 are
 * returned unchanged so the IPv4 parser / IPv6-unknown path can decide.
 *
 * @param {string} ip
 * @returns {string}
 */
function unwrapIpv4Mapped(ip) {
  const mapped = /(?:^|:)ffff:(\d{1,3}(?:\.\d{1,3}){3})$/i.exec(ip.trim());
  return mapped ? mapped[1] : ip;
}

/** Coarse IP family for diagnosing 'unknown' region. Never the address itself. */
const GEO_KIND = Object.freeze({
  IPV4: 'ipv4',
  IPV4_MAPPED: 'ipv4-mapped',
  IPV6: 'ipv6',
  IPV6_ULA: 'ipv6-ula',
  IPV6_CIDR: 'ipv6-cidr',
  EMPTY: 'empty',
  OTHER: 'other',
});

/**
 * Classify an address family without retaining it. Used to persist *why*
 * region is 'unknown' (Fly 6PN IPv6 vs native IPv6 vs unparseable) so we can
 * tell lookup-misses from "geo is IPv4-only".
 *
 * @param {unknown} ip
 * @returns {string} one of GEO_KIND values
 */
function classifyIp(ip) {
  if (typeof ip !== 'string') return GEO_KIND.EMPTY;
  const s = ip.trim();
  if (s === '') return GEO_KIND.EMPTY;
  const unwrapped = unwrapIpv4Mapped(s);
  const mapped = unwrapped !== s;
  if (ipv4ToInt(unwrapped) !== null) return mapped ? GEO_KIND.IPV4_MAPPED : GEO_KIND.IPV4;
  if (s.includes(':')) {
    if (s.includes('/')) return GEO_KIND.IPV6_CIDR;
    const head = s.toLowerCase();
    if (head.startsWith('fd') || head.startsWith('fc')) return GEO_KIND.IPV6_ULA;
    return GEO_KIND.IPV6;
  }
  return GEO_KIND.OTHER;
}

/**
 * Convert a dotted-quad IPv4 string (or IPv4-mapped IPv6) to its uint32 form,
 * or null if it is not a well-formed IPv4 address (native IPv6, garbage, empty).
 *
 * @param {unknown} ip
 * @returns {number|null}
 */
function ipv4ToInt(ip) {
  if (typeof ip !== 'string') return null;
  ip = unwrapIpv4Mapped(ip);
  const parts = ip.split('.');
  if (parts.length !== 4) return null;
  let acc = 0;
  for (let i = 0; i < 4; i++) {
    const octet = parts[i];
    // Reject empty, non-digit, or out-of-range octets. Disallow leading-zero
    // ambiguity beyond a single '0' to keep parsing strict.
    if (!/^\d{1,3}$/.test(octet)) return null;
    const n = Number(octet);
    if (n > 255) return null;
    if (octet.length > 1 && octet[0] === '0') return null;
    acc = acc * 256 + n;
  }
  // Coerce to unsigned 32-bit.
  return acc >>> 0;
}

/**
 * Parse a native IPv6 address into its /64 prefix as two big-endian uint32
 * words, or null. Rejects CIDR (`/56` rate-limit keys), zone IDs, dotted mixed
 * form, and anything that is not exactly 8 hextets after `::` expansion. The
 * low 64 bits are validated but dropped: the table carries no location below /64.
 *
 * @param {unknown} ip
 * @returns {{hi:number, lo:number}|null}
 */
function ipv6ToPrefix64(ip) {
  if (typeof ip !== 'string') return null;
  const s = ip.trim().toLowerCase();
  if (s === '' || s.includes('/') || s.includes('%') || s.includes('.')) return null;
  if (!s.includes(':')) return null;

  const sides = s.split('::');
  if (sides.length > 2) return null;

  const parseSide = (side) => {
    if (side === '') return [];
    const parts = side.split(':');
    const out = [];
    for (let i = 0; i < parts.length; i++) {
      const p = parts[i];
      if (!/^[0-9a-f]{1,4}$/.test(p)) return null;
      out.push(parseInt(p, 16));
    }
    return out;
  };

  let groups;
  if (sides.length === 1) {
    groups = parseSide(sides[0]);
    if (!groups || groups.length !== 8) return null;
  } else {
    const head = parseSide(sides[0]);
    const tail = parseSide(sides[1]);
    if (!head || !tail) return null;
    const missing = 8 - head.length - tail.length;
    if (missing < 1) return null;
    groups = head.concat(new Array(missing).fill(0), tail);
  }

  return {
    hi: ((groups[0] << 16) | groups[1]) >>> 0,
    lo: ((groups[2] << 16) | groups[3]) >>> 0,
  };
}

/** Compare two 64-bit values given as uint32 (hi, lo) word pairs. */
function cmp64(aHi, aLo, bHi, bLo) {
  if (aHi !== bHi) return aHi < bHi ? -1 : 1;
  if (aLo !== bLo) return aLo < bLo ? -1 : 1;
  return 0;
}

/**
 * Parse exactly 8 ASCII hex digits at buf[p..p+8) into a uint32, or -1.
 *
 * @param {Buffer} buf
 * @param {number} p
 * @param {number} end
 * @returns {number}
 */
function _parseHex32(buf, p, end) {
  if (p + 8 > end) return -1;
  let n = 0;
  for (let i = p; i < p + 8; i++) {
    const c = buf[i];
    let d;
    if (c >= 48 && c <= 57) d = c - 48;
    else if (c >= 97 && c <= 102) d = c - 87;
    else if (c >= 65 && c <= 70) d = c - 55;
    else return -1;
    n = n * 16 + d;
  }
  return n;
}

// ---------------------------------------------------------------------------
// Sorted line files, searched in place.
// ---------------------------------------------------------------------------

// Read size for each probe. Data lines are well under 200 bytes, so one read
// nearly always holds the line after the probe point.
const WINDOW_BYTES = 4096;
// A line longer than this is treated as corrupt rather than read further.
const MAX_LINE_BYTES = 64 * 1024;

const STOP = Symbol('stop');

function openSortedFile(filePath) {
  let fd = null;
  try {
    fd = fs.openSync(filePath, 'r');
    const { size } = fs.fstatSync(fd);
    if (size > 0) return { fd, size, buf: Buffer.allocUnsafe(MAX_LINE_BYTES) };
  } catch {
    // Absent / unreadable: fall through to the graceful null below.
  }
  if (fd !== null) { try { fs.closeSync(fd); } catch { /* ignore */ } }
  return null;
}

function closeSortedFile(file) {
  if (file) { try { fs.closeSync(file.fd); } catch { /* ignore */ } }
}

function ipv4File() {
  if (_ipv4File === undefined) _ipv4File = openSortedFile(resolveIpv4DatasetPath());
  return _ipv4File;
}

function ipv6File() {
  if (_ipv6File === undefined) _ipv6File = openSortedFile(resolveIpv6DatasetPath());
  return _ipv6File;
}

function placesFile() {
  if (_placesFile === undefined) _placesFile = openSortedFile(resolvePlacesDatasetPath());
  return _placesFile;
}

// Next newline (byte 10) in buf within [from, limit), or -1. The read buffer is
// reused, so its tail beyond `limit` holds stale bytes -- bound the search.
function _indexOfNewline(buf, from, limit) {
  const nl = buf.indexOf(10, from);
  return (nl < 0 || nl >= limit) ? -1 : nl;
}

/**
 * Call visit(buf, start, end, next) for each complete line whose first byte
 * lies in [from, limit), in file order. A line that began before `from` is
 * skipped: it belongs to the previous probe. `end` excludes the newline and a
 * trailing '\r'; `next` is the file offset of the following line. The first
 * non-undefined visit() result is returned.
 */
function forEachLine(file, from, limit, visit) {
  const { fd, size, buf } = file;
  let pos = from;

  if (pos > 0) {
    // Skip to just past the first newline at or after from-1.
    pos -= 1;
    for (;;) {
      if (pos >= size) return undefined;
      const n = fs.readSync(fd, buf, 0, WINDOW_BYTES, pos);
      if (n <= 0) return undefined;
      const nl = _indexOfNewline(buf, 0, n);
      if (nl !== -1) { pos += nl + 1; break; }
      pos += n;
    }
  }

  let window = WINDOW_BYTES;
  while (pos < limit && pos < size) {
    const n = fs.readSync(fd, buf, 0, window, pos);
    if (n <= 0) return undefined;
    let i = 0;
    while (i < n && pos + i < limit) {
      const nl = _indexOfNewline(buf, i, n);
      if (nl === -1 && pos + n < size) break; // line continues past this read
      const lineEnd = nl === -1 ? n : nl;
      const end = lineEnd > i && buf[lineEnd - 1] === 13 ? lineEnd - 1 : lineEnd;
      const result = visit(buf, i, end, pos + lineEnd + 1);
      if (result !== undefined) return result;
      if (nl === -1) return undefined; // last line, no trailing newline
      i = nl + 1;
    }
    if (pos + i >= limit) return undefined;
    if (i === 0) {
      // One line fills the whole read: widen it, or give up on a corrupt line.
      if (window >= MAX_LINE_BYTES) return undefined;
      window = Math.min(window * 2, MAX_LINE_BYTES);
    }
    pos += i;
  }
  return undefined;
}

/**
 * Binary-search a sorted line file. compare(buf, start, end) returns null for a
 * line that is not data (header comment, blank, malformed), a negative number
 * when the key sorts before the line, a positive one when after, and 0 on a
 * match, which decode(buf, start, end) turns into the return value. Returns
 * null when nothing matches.
 */
function searchSortedFile(file, compare, decode) {
  let lo = 0;
  let hi = file.size;
  // Invariant: a matching line, if any, starts in [lo, hi).
  while (hi - lo > WINDOW_BYTES) {
    const mid = lo + Math.floor((hi - lo) / 2);
    let nextAfterProbe = -1;
    const found = forEachLine(file, mid, hi, (buf, s, e, next) => {
      const c = compare(buf, s, e);
      if (c === null) return undefined;
      if (c === 0) return decode(buf, s, e);
      if (c > 0) nextAfterProbe = next;
      return STOP;
    });
    if (found !== undefined && found !== STOP) return found;
    if (nextAfterProbe >= 0) lo = nextAfterProbe;
    else hi = mid; // key sorts before the first data line at or after mid, or there is none
  }
  const found = forEachLine(file, lo, hi, (buf, s, e) => {
    const c = compare(buf, s, e);
    if (c === null || c > 0) return undefined;
    return c === 0 ? decode(buf, s, e) : STOP;
  });
  return found === undefined || found === STOP ? null : found;
}

// ---------------------------------------------------------------------------
// Range rows: bounds, then country,subdivision[,city]. Byte constants:
// 44=',' 35='#' 32=' ' 9='\t' 48..57='0'..'9'.
// ---------------------------------------------------------------------------

/** Offset of the first non-blank byte, or -1 for a blank or '#' comment line. */
function _dataStart(buf, start, end) {
  let p = start;
  while (p < end && (buf[p] === 32 || buf[p] === 9)) p++;
  return p >= end || buf[p] === 35 ? -1 : p;
}

/**
 * Offset just past the country field when buf[p..end) is `country,...` with a
 * non-empty country, else -1. Older files end at the subdivision; newer ones
 * add a city column.
 */
function _countryEnd(buf, p, end) {
  const cStart = p;
  while (p < end && buf[p] !== 44) p++;
  return p > cStart && p < end ? p : -1;
}

function _decodePlaceFields(buf, p, end) {
  const cEnd = _countryEnd(buf, p, end);
  const country = buf.toString('utf8', p, cEnd).trim();
  let q = cEnd + 1;
  while (q < end && buf[q] !== 44) q++;
  const subdivision = buf.toString('utf8', cEnd + 1, q).trim();
  const city = q < end ? buf.toString('utf8', q + 1, end).trim() : '';
  return { country, subdivision, city };
}

// DB-IP marks private/reserved space (RFC 1918, loopback, link-local, ULA incl.
// Fly 6PN) as country 'ZZ'. That is not a place, so it must not become a region.
const RESERVED_COUNTRY = 'ZZ';

function regionFromFields(fields) {
  return fields.country === RESERVED_COUNTRY ? 'unknown' : fields;
}

/** Parse an IPv4 row's bounds and label-field offset into `out`; false for a non-data line. */
function _parseIpv4Bounds(buf, start, end, out) {
  let p = _dataStart(buf, start, end);
  if (p < 0) return false;

  let lo = 0; let sawLo = false;
  while (p < end && buf[p] >= 48 && buf[p] <= 57) { lo = lo * 10 + (buf[p] - 48); p++; sawLo = true; }
  if (!sawLo || p >= end || buf[p] !== 44) return false;
  p++;

  let hi = 0; let sawHi = false;
  while (p < end && buf[p] >= 48 && buf[p] <= 57) { hi = hi * 10 + (buf[p] - 48); p++; sawHi = true; }
  if (!sawHi || p >= end || buf[p] !== 44) return false;
  p++;

  if (hi < lo || lo > 0xFFFFFFFF || _countryEnd(buf, p, end) < 0) return false;
  out.lo = lo; out.hi = hi; out.fields = p;
  return true;
}

function lookupIpv4(key) {
  const file = ipv4File();
  if (!file) return 'unknown';
  const row = { lo: 0, hi: 0, fields: 0 };
  const found = searchSortedFile(
    file,
    (buf, s, e) => {
      if (!_parseIpv4Bounds(buf, s, e, row)) return null;
      if (key < row.lo) return -1;
      return key > row.hi ? 1 : 0;
    },
    (buf, s, e) => {
      _parseIpv4Bounds(buf, s, e, row);
      return regionFromFields(_decodePlaceFields(buf, row.fields, e));
    }
  );
  return found || 'unknown';
}

/** Same for an IPv6 row, whose bounds are start64,end64 as exactly 16 hex digits each. */
function _parseIpv6Bounds(buf, start, end, out) {
  let p = _dataStart(buf, start, end);
  if (p < 0) return false;

  const startHi = _parseHex32(buf, p, end);
  const startLo = _parseHex32(buf, p + 8, end);
  if (startHi < 0 || startLo < 0 || p + 16 >= end || buf[p + 16] !== 44) return false;
  p += 17;

  const endHi = _parseHex32(buf, p, end);
  const endLo = _parseHex32(buf, p + 8, end);
  if (endHi < 0 || endLo < 0 || p + 16 >= end || buf[p + 16] !== 44) return false;
  p += 17;

  if (cmp64(endHi, endLo, startHi, startLo) < 0 || _countryEnd(buf, p, end) < 0) return false;
  out.startHi = startHi; out.startLo = startLo;
  out.endHi = endHi; out.endLo = endLo;
  out.fields = p;
  return true;
}

function lookupIpv6(hi, lo) {
  const file = ipv6File();
  if (!file) return 'unknown';
  const row = { startHi: 0, startLo: 0, endHi: 0, endLo: 0, fields: 0 };
  const found = searchSortedFile(
    file,
    (buf, s, e) => {
      if (!_parseIpv6Bounds(buf, s, e, row)) return null;
      if (cmp64(hi, lo, row.startHi, row.startLo) < 0) return -1;
      return cmp64(hi, lo, row.endHi, row.endLo) > 0 ? 1 : 0;
    },
    (buf, s, e) => {
      _parseIpv6Bounds(buf, s, e, row);
      return regionFromFields(_decodePlaceFields(buf, row.fields, e));
    }
  );
  return found || 'unknown';
}

/**
 * Derive a coarse { country, subdivision, city } place from a plaintext IP, or
 * the literal string 'unknown' when the IP falls outside every range, lands in
 * DB-IP's reserved 'ZZ' space, or no dataset is present. `city` is '' when the
 * dataset row has none (including the older state-level files). IPv4
 * (including mapped ::ffff:a.b.c.d) uses the IPv4 table; native IPv6 uses the
 * sibling IPv6 table. NEVER throws; NEVER retains or logs the IP.
 *
 * @param {string} ip plaintext request IP (Fly-Client-IP / req.ip)
 * @returns {{country:string, subdivision:string, city:string}|'unknown'}
 */
function deriveRegion(ip) {
  try {
    const key = ipv4ToInt(ip);
    if (key !== null) return lookupIpv4(key);
    const prefix = ipv6ToPrefix64(ip);
    return prefix ? lookupIpv6(prefix.hi, prefix.lo) : 'unknown';
  } catch {
    return 'unknown';
  }
}

// ---------------------------------------------------------------------------
// Place centroids: label,lat,lon sorted by label.
// ---------------------------------------------------------------------------

/** Byte offset of the comma ending the label, or -1 for a non-data line. */
function _placeLabelEnd(buf, start, end) {
  const p = _dataStart(buf, start, end);
  if (p < 0) return -1;
  let q = p;
  while (q < end && buf[q] !== 44) q++;
  return q > p && q < end ? q : -1;
}

function _decodeCentroid(buf, labelEnd, end) {
  let q = labelEnd + 1;
  while (q < end && buf[q] !== 44) q++;
  if (q >= end) return null;
  const lat = Number(buf.toString('latin1', labelEnd + 1, q));
  const lon = Number(buf.toString('latin1', q + 1, end));
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
  if (lat < -90 || lat > 90 || lon < -180 || lon > 180) return null;
  return { lat, lon };
}

/**
 * Approximate centroid of a region label ('US', 'US-CA', 'US-CA/San Jose'), or
 * null when the label is not in the places file (or there is no file). This is
 * where the place is, from the dataset -- never where an install is.
 *
 * @param {string} label
 * @returns {{lat:number, lon:number}|null}
 */
function placeCentroid(label) {
  if (typeof label !== 'string' || label === '' || label === 'unknown' || label === 'Other') return null;
  try {
    const file = placesFile();
    if (!file) return null;
    return searchSortedFile(
      file,
      (buf, s, e) => {
        const labelEnd = _placeLabelEnd(buf, s, e);
        if (labelEnd < 0) return null;
        const lineLabel = buf.toString('utf8', _dataStart(buf, s, e), labelEnd);
        if (label < lineLabel) return -1;
        return label > lineLabel ? 1 : 0;
      },
      (buf, s, e) => _decodeCentroid(buf, _placeLabelEnd(buf, s, e), e)
    );
  } catch {
    return null;
  }
}

/**
 * Test-only: close the cached files so a test can re-point dataset paths and
 * force a fresh open. Not used in production code paths.
 */
function _resetForTest() {
  closeSortedFile(_ipv4File);
  closeSortedFile(_ipv6File);
  closeSortedFile(_placesFile);
  _ipv4File = undefined;
  _ipv6File = undefined;
  _placesFile = undefined;
}

